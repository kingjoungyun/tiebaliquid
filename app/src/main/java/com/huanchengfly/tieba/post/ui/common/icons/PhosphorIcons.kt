    /** 取一个 Phosphor 图标；名字不存在返回 null（调用方回退到别的图标集）。 */
    operator fun get(name: String): ImageVector? {
        cache[name]?.let { return it }
        val data = paths[name] ?: return null
        return build(name, data).also { cache[name] = it }
    }

    fun contains(name: String): Boolean = paths.containsKey(name)

    private fun build(name: String, data: List<String>): ImageVector {
        var builder = ImageVector.Builder(
            name = "phosphor.$name",
            defaultWidth = 24.dp,
            defaultHeight = 24.dp,
            viewportWidth = 256f,
            viewportHeight = 256f,
        )
        data.forEach { d ->
            builder = builder.addPath(
                pathData = addPathNodes(d),
                fill = SolidColor(Color.Black),
                fillAlpha = 1f,
                stroke = null,
                strokeAlpha = 1f,
                // Phosphor 的 fill 变体靠 evenOdd 挖洞（例如眼罩的瞳孔），
                // 用 NonZero 会把洞填死。
                pathFillType = PathFillType.EvenOdd,
            )
        }
        return builder.build()
    }
